def get_map_points_by_domain(domain=None):
    if not domain or domain == 'all':
        return MAP_POINTS
    return [p for p in MAP_POINTS if p.get('domain') == domain]

def get_map_pointing_quiz_questions(domain=None):
    pts = get_map_points_by_domain(domain)
    quizzes = []
    for p in pts:
        if 'quiz' in p:
            q_data = p['quiz']
            quizzes.append({
                'id': p['id'],
                'domain': p['domain'],
                'location_name': p['telugu_name'],
                'question': q_data['q'],
                'options': q_data['options'],
                'answer': q_data['ans'],
                'explanation': q_data['exp'],
                'pyq_note': p.get('pyq', '')
            })
    return quizzes
