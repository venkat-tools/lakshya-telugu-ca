def get_appsc_group2_pyqs(year=None):
    """Returns authentic APPSC Group 2 Previous Year Questions."""
    if year:
        return [q for q in ALL_APPSC_GROUP2_QUESTIONS if q["is_pyq"] and str(q["pyq_year"]) == str(year)]
    return [q for q in ALL_APPSC_GROUP2_QUESTIONS if q["is_pyq"]]

def get_appsc_group2_quick_test(count=50):
    """Returns a mini 50-question grand test (10 from each of the 5 sections)."""
    quick_qs = []
    sections = ["history", "geography", "society", "current_affairs", "mental_ability"]
    per_section = count // len(sections)
    for sec in sections:
        sec_qs = [q for q in ALL_APPSC_GROUP2_QUESTIONS if q["section_id"] == sec]
        quick_qs.extend(sec_qs[:per_section])
    return quick_qs

