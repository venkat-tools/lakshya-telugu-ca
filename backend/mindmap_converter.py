def is_mindmap_font(text: str) -> bool:
    """Returns True if text contains signature glyphs of CIDFont/Mindmap Telugu."""
    if not text:
        return False
    signature_tokens = [
        "şలంæò", "фѓȚ", "ăతĂహ", "ąĀరȰంȆ", "ąంċక", "సంసȩరణѠ",
        "చĢʥ", "వɂవసȹ", "Бëం", "Пěక", "éѡфɂ", "ĦѤȷфం",
        "фѓȚ ĄĪѠ", "అసș ëŎ"
    ]
    for sig in signature_tokens:
        if sig in text:
            return True
    
    # Check count of specific Latin-Extended / Cyrillic / IPA characters
    test_chars = "ѠĢʥøąċčќфѓĄĪŎëşæòǘБĆʨɂȹȰȆĀƅĠĤġćɇѤȷĔїƒéѡęƚŮƘȚș"
    count = sum(text.count(c) for c in test_chars)
    return count >= 4

def convert_mindmap_to_unicode(text: str) -> str:
    """Converts CIDFont mindmap glyphs to clean Telugu Unicode."""
    if not text:
        return text
    
    result = text
    for glyph, repl in MINDMAP_MAP:
        result = result.replace(glyph, repl)
    
    return result
