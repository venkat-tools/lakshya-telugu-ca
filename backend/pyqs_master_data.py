def get_all_pyq_questions():
    all_qs = []
    for p_id, p in PYQ_PAPERS.items():
        for q in p.get("questions", []):
            item = dict(q)
            item["paper_title"] = p["title"]
            item["paper_id"] = p_id
            all_qs.append(item)
    return all_qs
